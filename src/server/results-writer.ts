import { writeFile, mkdir } from "fs/promises";
import { join } from "path";
import type { ServerJob, ServerTask, ServerWorker } from "./types";
import type { WireArtifact, WireResult } from "../lib/shared-types";

const RESULTS_DIR = join(process.cwd(), "results");

function sanitizeFilename(value: string): string {
  return value
    .toLowerCase()
    .replace(/[^a-z0-9-_]+/g, "-")
    .replace(/-{2,}/g, "-")
    .replace(/^-+|-+$/g, "")
    .slice(0, 80);
}

function formatDuration(ms: number): string {
  const s = Math.floor(ms / 1000);
  const m = Math.floor(s / 60);
  if (m > 0) return `${m}m ${s % 60}s`;
  return `${s}.${String(ms % 1000).padStart(3, "0")}s`;
}

function formatDate(ts: number): string {
  return new Date(ts).toISOString().replace("T", " ").replace(/\.\d+Z$/, " UTC");
}

export async function writeResultsMd(
  job: ServerJob,
  tasks: ServerTask[],
  result: WireResult,
  workers: ServerWorker[]
): Promise<string> {
  await mkdir(RESULTS_DIR, { recursive: true });

  const completedTasks = tasks.filter((t) => t.status === "completed");
  const failedTasks = tasks.filter((t) => t.status === "failed");
  const workerIds = new Set(completedTasks.map((t) => t.assignedWorkerId).filter(Boolean));
  const involvedWorkers = workers.filter((w) => workerIds.has(w.id));

  const lines: string[] = [];

  // Header
  lines.push(`# ${job.title}`);
  lines.push("");
  lines.push(`> Job ID: \`${job.id}\` | Session: \`${job.sessionCode}\``);
  lines.push("");

  // Summary table
  lines.push("## Summary");
  lines.push("");
  lines.push("| Metric | Value |");
  lines.push("|--------|-------|");
  lines.push(`| **Status** | ${job.status === "completed" ? "Completed" : "Failed"} |`);
  lines.push(`| **Job Type** | ${job.jobType} |`);
  lines.push(`| **Total Compute Time** | ${formatDuration(result.durationMs)} |`);
  lines.push(`| **Tasks** | ${completedTasks.length} completed, ${failedTasks.length} failed / ${tasks.length} total |`);
  lines.push(`| **Workers Used** | ${result.workerCount} |`);
  lines.push(`| **Data Processed** | ${result.dataProcessed} |`);
  if (typeof result.metrics.totalOps === "number") {
    lines.push(`| **Total Operations** | ${Number(result.metrics.totalOps).toLocaleString()} |`);
  }
  if (typeof result.metrics.successRate === "number") {
    lines.push(`| **Success Rate** | ${result.metrics.successRate}% |`);
  }
  lines.push(`| **Started At** | ${job.startedAt ? formatDate(job.startedAt) : "—"} |`);
  lines.push(`| **Completed At** | ${job.completedAt ? formatDate(job.completedAt) : "—"} |`);
  lines.push("");

  // Task breakdown
  lines.push("## Task Results");
  lines.push("");
  lines.push("| # | Task | Worker | Status | Duration | Operations | Efficiency |");
  lines.push("|---|------|--------|--------|----------|------------|------------|");

  for (let i = 0; i < tasks.length; i++) {
    const task = tasks[i];
    const output = task.outputPayload as Record<string, unknown> | undefined;
    const worker = involvedWorkers.find((w) => w.id === task.assignedWorkerId);
    const workerName = worker?.name ?? task.assignedWorkerId ?? "—";
    const status = task.status === "completed" ? "Done" : task.status === "failed" ? "FAILED" : task.status;
    const durationMs = task.completedAt && task.startedAt
      ? task.completedAt - task.startedAt
      : typeof output?.durationMs === "number" ? output.durationMs as number : 0;
    const ops = typeof output?.opsCount === "number" ? Number(output.opsCount).toLocaleString() : "—";
    const eff = typeof output?.efficiency === "number"
      ? `${(Number(output.efficiency) * 100).toFixed(1)}%`
      : output?.tileRendered ? "rendered" : "—";

    lines.push(`| ${i + 1} | ${task.title} | ${workerName} | ${status} | ${formatDuration(durationMs)} | ${ops} | ${eff} |`);
  }
  lines.push("");

  // Worker nodes
  lines.push("## Compute Nodes");
  lines.push("");
  lines.push("| Worker | Device | Tasks Done | Avg Task Duration | Performance Tier |");
  lines.push("|--------|--------|------------|-------------------|------------------|");

  for (const w of involvedWorkers) {
    const avgMs = w.tasksCompleted > 0 ? Math.round(w.totalTaskDurationMs / w.tasksCompleted) : 0;
    const tier = w.benchmark?.performanceTier ?? "—";
    lines.push(`| ${w.name} | ${w.device} | ${w.tasksCompleted} | ${formatDuration(avgMs)} | ${tier} |`);
  }
  lines.push("");

  // Result output
  lines.push("## Output");
  lines.push("");
  lines.push("```");
  for (const line of result.outputLines) {
    lines.push(line);
  }
  lines.push("```");
  lines.push("");

  if (result.summary) {
    lines.push(`**Summary:** ${result.summary}`);
    lines.push("");
  }

  // Footer
  lines.push("---");
  lines.push(`*Generated by Clementine at ${formatDate(Date.now())}*`);
  lines.push("");

  const content = lines.join("\n");
  const filename = `${job.id}_${job.jobType}_${Date.now()}.md`;
  const filepath = join(RESULTS_DIR, filename);
  await writeFile(filepath, content, "utf-8");

  console.log(`[results] Written ${filepath}`);
  return filepath;
}

export async function writeMarkdownArtifact(filenameBase: string, content: string): Promise<string> {
  await mkdir(RESULTS_DIR, { recursive: true });
  const safeBase = sanitizeFilename(filenameBase) || `artifact-${Date.now()}`;
  const filepath = join(RESULTS_DIR, `${safeBase}.md`);
  await writeFile(filepath, content, "utf-8");
  console.log(`[results] Written ${filepath}`);
  return filepath;
}

export function buildJobResultMarkdown(job: ServerJob, result: WireResult): string {
  const lines: string[] = [];
  const trimmedOutput = result.outputLines
    .map((line) => line.trim())
    .filter(Boolean)
    .slice(0, 18);

  lines.push(`# ${job.title}`);
  lines.push("");
  lines.push(`> Job ID: \`${job.id}\` | Session: \`${job.sessionCode}\` | Type: \`${job.jobType}\``);
  lines.push("");
  lines.push("## Executive Summary");
  lines.push(result.summary || "Job completed successfully.");
  lines.push("");
  lines.push("## Metrics");
  lines.push("");
  lines.push("| Metric | Value |");
  lines.push("|--------|-------|");
  lines.push(`| Status | ${job.status} |`);
  lines.push(`| Duration | ${formatDuration(result.durationMs)} |`);
  lines.push(`| Workers Used | ${result.workerCount} |`);
  lines.push(`| Completed Tasks | ${job.completedTasks}/${job.totalTasks} |`);
  lines.push(`| Failed Tasks | ${job.failedTasks} |`);
  lines.push(`| Data Processed | ${result.dataProcessed} |`);
  if (typeof result.metrics.totalOps === "number") {
    lines.push(`| Total Operations | ${Number(result.metrics.totalOps).toLocaleString()} |`);
  }
  if (typeof result.metrics.successRate === "number") {
    lines.push(`| Success Rate | ${result.metrics.successRate}% |`);
  }
  lines.push("");
  lines.push("## Result Notes");
  lines.push("");
  if (trimmedOutput.length > 0) {
    trimmedOutput.forEach((line) => {
      lines.push(`- ${line}`);
    });
  } else {
    lines.push("- No additional output lines were recorded.");
  }
  lines.push("");
  lines.push("---");
  lines.push(`*Generated by Clementine at ${formatDate(Date.now())}*`);
  lines.push("");
  return lines.join("\n");
}

export async function createJobResultArtifact(
  job: ServerJob,
  result: WireResult
): Promise<WireArtifact> {
  const content = buildJobResultMarkdown(job, result);
  const filenameBase = `${job.id}-${job.jobType}-result`;
  const filePath = await writeMarkdownArtifact(filenameBase, content);

  return {
    id: `artifact_${job.id}_result_markdown`,
    jobId: job.id,
    artifactType: "markdown",
    title: `${job.title} Result`,
    filename: `${sanitizeFilename(filenameBase)}.md`,
    content,
    createdAt: Date.now(),
    filePath,
  };
}
